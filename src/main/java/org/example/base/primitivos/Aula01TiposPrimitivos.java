package org.example.base.primitivos;

public class Aula01TiposPrimitivos {
    public static void main(String[] args) {
        // int, double, float, char, boolean, byte, short, long
        int idade = 30;
        double salario = 2000.50;
        float altura = 1.75f;
        char sexo = 'M';
        boolean casado = false;
        short numeroCurto = 100;
        long numeroLongo = 1000000000L;
        byte numeroByte = 127;
        String nome = "João";

        System.out.println("Idade: " + idade + " anos");
        System.out.println("Salário: R$ " + salario);
        System.out.println("Altura: " + altura + " m");
    }
}
